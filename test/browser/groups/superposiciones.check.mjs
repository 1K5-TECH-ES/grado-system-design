// Pruebas en navegador · grupo «superposiciones y acciones»: teclado, foco y comportamiento, en React y en Vue.
// Se ejecuta antes de la pasada de axe, que también revisa lo que pinta superposiciones.fixture.mjs.
// check(page, { expect, framework })
export async function check(page, { expect }) {
  // Posición final, sin la animación de entrada a medias.
  const settled = async (locator) => {
    await locator.evaluate((el) => Promise.all(el.getAnimations().map((a) => a.finished)))
    return locator.boundingBox()
  }
  // Popover: abre con teclado y lleva el foco dentro; Escape y clic fuera lo cierran y devuelven el foco.
  const popover = page.locator('#sp-popover .k5-popover').first()
  const trigger = popover.locator('[aria-haspopup=dialog]')
  await expect(trigger).toHaveAttribute('aria-expanded', 'false')
  await trigger.focus()
  await page.keyboard.press('Enter')
  const panel = popover.locator('[role=dialog]')
  await expect(panel).toBeVisible()
  await expect(panel).toHaveAccessibleName('ES0021000000000001AB')
  await expect(trigger).toHaveAttribute('aria-expanded', 'true')
  await expect(trigger).toHaveAttribute('aria-controls', (await panel.getAttribute('id')) ?? '')
  await expect(panel.locator('button')).toBeFocused()
  await page.keyboard.press('Escape')
  await expect(panel).toHaveCount(0)
  await expect(trigger).toBeFocused()
  await trigger.click()
  await expect(panel.locator('button')).toBeFocused()
  await page.locator('#sp-popover').click({ position: { x: 600, y: 8 } })
  await expect(panel).toHaveCount(0)
  await expect(trigger).toBeFocused()
  // Sin controles dentro, el foco va al panel; Tab fuera lo cierra.
  const help = page.locator('#sp-popover .k5-popover').last()
  await help.locator('[aria-haspopup=dialog]').click()
  await expect(help.locator('[role=dialog]')).toBeFocused()
  await expect(help.locator('[role=dialog]')).toHaveAccessibleName('Ayuda')
  const box = await settled(help.locator('[role=dialog]'))
  expect(box.x).toBeGreaterThanOrEqual(0)
  await page.keyboard.press('Escape')
  await expect(help.locator('[role=dialog]')).toHaveCount(0)

  // Banner: se cierra con su botón; danger se anuncia como alerta.
  await expect(page.locator('#sp-banner .k5-banner--danger')).toHaveAttribute('role', 'alert')
  await page.locator('#sp-banner .k5-banner--warning .k5-close').click()
  await expect(page.locator('#sp-banner .k5-banner--warning')).toHaveCount(0)

  // ContextMenu: clic derecho en la posición del puntero, flechas que saltan lo desactivado y Enter.
  const zone = page.locator('#sp-context .k5-context-menu')
  const menu = zone.locator('[role=menu]')
  // En el centro de la ventana, para que el menú quepa debajo del puntero.
  await zone.evaluate((el) => el.scrollIntoView({ block: 'center' }))
  const zoneBox = await zone.boundingBox()
  await zone.click({ button: 'right', position: { x: 40, y: 10 } })
  await expect(menu).toBeVisible()
  const menuBox = await settled(menu)
  expect(Math.abs(menuBox.x - (zoneBox.x + 40))).toBeLessThan(2)
  expect(Math.abs(menuBox.y - (zoneBox.y + 10))).toBeLessThan(2)
  await expect(menu.locator('[role=menuitem]').first()).toBeFocused()
  await page.keyboard.press('ArrowDown')
  await expect(menu.locator('[role=menuitem]').last()).toBeFocused()
  await page.keyboard.press('Enter')
  await expect(menu).toHaveCount(0)
  await expect(page.locator('#sp-context output')).toHaveText('baja')
  await expect(zone).toBeFocused()
  // Mayúsculas + F10 con la zona enfocada: se ancla a la zona. Escape cierra y devuelve el foco.
  await page.keyboard.press('Shift+F10')
  await expect(menu).toBeVisible()
  const anchored = await settled(menu)
  expect(Math.abs(anchored.x - zoneBox.x)).toBeLessThan(2)
  await expect(menu.locator('[role=menuitem]').first()).toBeFocused()
  await page.keyboard.press('End')
  await expect(menu.locator('[role=menuitem]').last()).toBeFocused()
  await page.keyboard.press('Escape')
  await expect(menu).toHaveCount(0)
  await expect(zone).toBeFocused()
  await page.keyboard.press('ContextMenu')
  await expect(menu).toBeVisible()
  await page.keyboard.press('Enter')
  await expect(page.locator('#sp-context output')).toHaveText('abrir')
  // Cerca del borde derecho de la ventana, el menú se abre hacia dentro.
  const width = await page.evaluate(() => document.documentElement.clientWidth)
  await page.evaluate(() => document.querySelector('#sp-context .k5-context-menu').style.setProperty('width', '100vw'))
  const top = (await zone.boundingBox()).y
  await page.mouse.click(width - 5, top + 10, { button: 'right' })
  const inside = await settled(menu)
  expect(inside.x + inside.width).toBeLessThanOrEqual(width)
  await page.mouse.click(5, 5)
  await expect(menu).toHaveCount(0)
  await page.evaluate(() => document.querySelector('#sp-context .k5-context-menu').style.removeProperty('width'))

  // ActionBar: flota abajo y centrada; flechas entre botones y Escape quita la selección.
  await expect(page.locator('#sp-action .k5-action-bar:not(.k5-action-bar--inline)')).toHaveCount(0)
  await page.locator('#sp-action > button').click()
  const bar = page.locator('#sp-action [role=toolbar]').first()
  await expect(bar).toHaveAccessibleName('3 seleccionadas')
  const barBox = await settled(bar)
  const viewport = page.viewportSize()
  expect(Math.abs(barBox.x + barBox.width / 2 - viewport.width / 2)).toBeLessThan(2)
  expect(viewport.height - (barBox.y + barBox.height)).toBeLessThan(40)
  await page.keyboard.press('Tab')
  const tools = bar.locator('button')
  await expect(tools.first()).toBeFocused()
  await page.keyboard.press('ArrowRight')
  await expect(tools.nth(1)).toBeFocused()
  await page.keyboard.press('ArrowRight')
  await expect(tools.last()).toHaveText('Quitar selección')
  await expect(tools.last()).toBeFocused()
  await page.keyboard.press('ArrowRight')
  await expect(tools.first()).toBeFocused()
  await page.keyboard.press('ArrowLeft')
  await expect(tools.last()).toBeFocused()
  await page.keyboard.press('Escape')
  await expect(page.locator('#sp-action output')).toHaveText('1')
  await expect(page.locator('#sp-action [role=toolbar]')).toHaveCount(1)
  await expect(page.locator('#sp-action > button')).toBeFocused()
  await page.locator('#sp-action > button').click()
  await bar.getByText('Quitar selección').click()
  await expect(page.locator('#sp-action output')).toHaveText('2')

  // IconButton conmutado: aria-pressed sigue al estado, con ratón y con teclado.
  const pin = page.locator('#sp-icon button').first()
  await expect(pin).toHaveAccessibleName('Fijar instalación')
  await expect(pin).toHaveAttribute('aria-pressed', 'false')
  await pin.click()
  await expect(pin).toHaveAttribute('aria-pressed', 'true')
  await expect(page.locator('#sp-icon output')).toHaveText('true')
  await page.keyboard.press('Space')
  await expect(pin).toHaveAttribute('aria-pressed', 'false')
  const own = page.locator('#sp-icon button').nth(1)
  await expect(own).toHaveAttribute('aria-pressed', 'true')
  await own.click()
  await expect(own).toHaveAttribute('aria-pressed', 'false')
  await expect(page.locator('#sp-icon button').last()).not.toHaveAttribute('aria-pressed')

  // ToggleGroup single: un punto de Tab, flechas mueven el foco sin elegir, Enter elige y vuelve a quitar.
  const single = page.locator('#sp-single button')
  await expect(page.locator('#sp-single [role=group]')).toHaveAccessibleName('Formato del texto')
  await expect(page.locator('#sp-single [tabindex="0"]')).toHaveCount(1)
  await single.first().focus()
  await page.keyboard.press('Space')
  await expect(page.locator('#sp-single output')).toHaveText('b')
  await page.keyboard.press('ArrowRight')
  await expect(single.nth(1)).toBeFocused()
  await expect(page.locator('#sp-single output')).toHaveText('b')
  await expect(single.nth(1)).toHaveAttribute('tabindex', '0')
  await page.keyboard.press('Enter')
  await expect(page.locator('#sp-single output')).toHaveText('i')
  await expect(single.first()).toHaveAttribute('aria-pressed', 'false')
  await page.keyboard.press('ArrowRight')
  await expect(single.first()).toBeFocused()
  await page.keyboard.press('End')
  await expect(single.nth(1)).toBeFocused()
  await page.keyboard.press('Enter')
  await expect(page.locator('#sp-single output')).toHaveText('')
  await expect(page.locator('#sp-single [aria-pressed=true]')).toHaveCount(0)

  // ToggleGroup multiple: solo iconos con nombre, varias activas a la vez.
  const multi = page.locator('#sp-multi button')
  await expect(multi.first()).toHaveAccessibleName('Conectadas')
  await multi.first().click()
  await page.keyboard.press('ArrowRight')
  await expect(multi.nth(1)).toBeFocused()
  await page.keyboard.press('Space')
  await expect(page.locator('#sp-multi output')).toHaveText('conectadas,obra')
  await page.keyboard.press('Home')
  await page.keyboard.press('Space')
  await expect(page.locator('#sp-multi output')).toHaveText('obra')
  await page.keyboard.press('ArrowLeft')
  await expect(multi.last()).toBeFocused()

  // El Popover queda abierto para que axe revise también el panel.
  await trigger.click()
  await expect(panel).toBeVisible()
}
