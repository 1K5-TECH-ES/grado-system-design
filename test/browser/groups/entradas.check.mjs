// Se ejecuta antes de la pasada de axe, que también revisa lo que pinta entradas.fixture.mjs.
// check(page, { expect, framework })
import { readFileSync } from 'node:fs'
import { createRequire } from 'node:module'

// axe-core sobre una sección, para revisar las listas abiertas (la pasada general las ve cerradas).
const axeSource = readFileSync(createRequire(import.meta.url).resolve('axe-core/axe.min.js'), 'utf8')
async function axeOn(page, selector, expect) {
  if (!(await page.evaluate(() => 'axe' in window))) await page.addScriptTag({ content: axeSource })
  const tags = ['wcag2a', 'wcag2aa', 'wcag21a', 'wcag21aa', 'wcag22aa']
  const problems = await page.evaluate(
    ([target, values]) =>
      window.axe
        .run(target, { runOnly: { type: 'tag', values } })
        .then((result) => result.violations.map((v) => `${v.id}: ${v.nodes.map((n) => n.target.join(' ')).join(' | ')}`)),
    [selector, tags],
  )
  expect(problems, selector).toEqual([])
}

export async function check(page, { expect }) {
  // SearchInput: el botón de borrar aparece con texto; Escape borra sin perder el foco.
  const search = page.locator('#entradas-search input[type=search]')
  const clear = page.locator('#entradas-search .k5-input-action')
  await expect(search).toHaveAccessibleName('Buscar cliente')
  await expect(clear).toHaveCount(0)
  await search.fill('Fernández')
  await expect(page.locator('#entradas-search output')).toHaveText('Fernández')
  await expect(clear).toHaveAccessibleName('Borrar búsqueda')
  await search.press('Escape')
  await expect(search).toHaveValue('')
  await expect(page.locator('#entradas-search output')).toHaveText('')
  await expect(search).toBeFocused()
  await expect(clear).toHaveCount(0)
  await search.fill('Ruiz')
  await clear.click()
  await expect(search).toHaveValue('')
  await expect(search).toBeFocused()

  // PasswordInput: el botón muestra y oculta la contraseña y lo dice con aria-pressed.
  const password = page.locator('#entradas-password input')
  const eye = page.locator('#entradas-password .k5-input-action')
  await password.fill('Solar2026')
  await expect(password).toHaveAttribute('type', 'password')
  await expect(password).toHaveAttribute('autocomplete', 'current-password')
  await expect(eye).toHaveAccessibleName('Mostrar contraseña')
  await expect(eye).toHaveAttribute('aria-pressed', 'false')
  await eye.focus()
  await page.keyboard.press('Space')
  await expect(password).toHaveAttribute('type', 'text')
  await expect(eye).toHaveAttribute('aria-pressed', 'true')
  await expect(eye).toHaveAttribute('title', 'Ocultar contraseña')
  await expect(eye).toBeFocused()
  await page.keyboard.press('Enter')
  await expect(password).toHaveAttribute('type', 'password')
  await expect(password).toHaveValue('Solar2026')

  // Slider: flechas, Inicio y Fin del input range nativo; el valor se anuncia con su unidad.
  const slider = page.locator('#entradas-slider input[type=range]')
  await expect(slider).toHaveAccessibleName('Potencia')
  await slider.focus()
  await page.keyboard.press('ArrowRight')
  await expect(page.locator('#entradas-slider output').last()).toHaveText('8.5')
  await expect(slider).toHaveAttribute('aria-valuetext', '8,5 kWp')
  await expect(page.locator('#entradas-slider .k5-slider__value')).toHaveText('8,5 kWp')
  await page.keyboard.press('ArrowLeft')
  await page.keyboard.press('ArrowLeft')
  await expect(page.locator('#entradas-slider output').last()).toHaveText('7.5')
  await page.keyboard.press('End')
  await expect(slider).toHaveAttribute('aria-valuetext', '17 kWp')
  await page.keyboard.press('Home')
  await expect(page.locator('#entradas-slider output').last()).toHaveText('2')
  expect(await slider.evaluate((el) => getComputedStyle(el.closest('.k5-slider')).getPropertyValue('--_fill').trim())).toBe('0')

  // TimePicker: «930» queda «09:30» al salir; al abrir, la franja elegida está activa.
  const time = page.locator('#entradas-time input[role=combobox]')
  const timeOut = page.locator('#entradas-time output')
  await time.fill('930')
  await time.press('Tab')
  await expect(time).toHaveValue('09:30')
  await expect(timeOut).toHaveText('09:30')
  await expect(time).toHaveAttribute('aria-expanded', 'false')
  await time.focus()
  await expect(time).toHaveAttribute('aria-expanded', 'true')
  const activeId = await time.getAttribute('aria-activedescendant')
  await expect(page.locator(`#${activeId}`)).toHaveText('09:30')
  await expect(page.locator(`#${activeId}`)).toHaveAttribute('aria-selected', 'true')
  await page.keyboard.press('ArrowDown')
  await page.keyboard.press('ArrowDown')
  await expect(page.locator(`#${await time.getAttribute('aria-activedescendant')}`)).toHaveText('10:00')
  await page.keyboard.press('Enter')
  await expect(timeOut).toHaveText('10:00')
  await expect(time).toHaveValue('10:00')
  await expect(time).toHaveAttribute('aria-expanded', 'false')
  await expect(time).toBeFocused()
  // Fuera de rango y formato: el texto se queda con su error, enlazado al campo.
  await time.fill('2130')
  await time.press('Tab')
  await expect(page.locator('#entradas-time .k5-field__error')).toHaveText('Elige una hora hasta las 20:00.')
  await expect(time).toHaveAttribute('aria-invalid', 'true')
  await expect(time).toHaveValue('21:30')
  await expect(timeOut).toHaveText('')
  await time.fill('9:7')
  await time.press('Tab')
  await expect(page.locator('#entradas-time .k5-field__error')).toHaveText('Escribe la hora como 09:30.')
  await time.fill('8.15')
  await time.press('Escape')
  await time.press('Enter')
  await expect(timeOut).toHaveText('08:15')
  await expect(page.locator('#entradas-time .k5-field__error')).toHaveCount(0)
  await time.press('Escape')
  await time.press('Tab')

  // PhoneInput: agrupa al escribir y devuelve E.164; el prefijo cambia el país.
  const phone = page.locator('#entradas-phone input[type=tel]')
  const phoneOut = page.locator('#entradas-phone output')
  await phone.pressSequentially('612345678')
  await expect(phone).toHaveValue('612 345 678')
  await expect(phoneOut).toHaveText('+34612345678')
  await page.locator('#entradas-phone select').selectOption('FR')
  await expect(phoneOut).toHaveText('+33612345678')
  await expect(phone).toHaveValue('6 12 34 56 78')
  await page.locator('#entradas-phone select').selectOption('ES')
  // Cursor en medio: borra una cifra y sigue escribiendo en el mismo sitio.
  await phone.focus()
  await page.keyboard.press('End')
  await page.keyboard.press('ArrowLeft')
  await page.keyboard.press('ArrowLeft')
  await page.keyboard.press('ArrowLeft')
  await page.keyboard.press('ArrowLeft')
  await page.keyboard.press('Backspace')
  await page.keyboard.type('9')
  await expect(phone).toHaveValue('612 349 678')
  await phone.fill('51234')
  await phone.blur()
  await expect(page.locator('#entradas-phone .k5-field__error')).toHaveText('Un teléfono español tiene 9 cifras.')
  await expect(phone).toHaveAttribute('aria-invalid', 'true')
  await phone.fill('+351 912 345 678')
  await expect(page.locator('#entradas-phone select')).toHaveValue('PT')
  await expect(phoneOut).toHaveText('+351912345678')
  await expect(page.locator('#entradas-phone .k5-field__error')).toHaveCount(0)

  // NifInput: mayúsculas sin guiones y el error concreto de la letra.
  const nif = page.locator('#entradas-nif input')
  await nif.fill('12345678-a')
  await expect(nif).toHaveValue('12345678A')
  await nif.blur()
  const nifError = page.locator('#entradas-nif .k5-field__error')
  await expect(nifError).toHaveText('La letra del DNI no coincide.')
  await expect(nif).toHaveAttribute('aria-invalid', 'true')
  expect(await nif.getAttribute('aria-describedby')).toContain(await nifError.getAttribute('id'))
  await nif.fill('x1234567l')
  await expect(nif).toHaveValue('X1234567L')
  await expect(nifError).toHaveCount(0)
  await expect(page.locator('#entradas-nif output')).toHaveText('X1234567L')

  // IbanInput: grupos de cuatro al escribir, valor sin espacios y control módulo 97.
  const iban = page.locator('#entradas-iban input')
  await iban.pressSequentially('es9121000418450200051333')
  await expect(iban).toHaveValue('ES91 2100 0418 4502 0005 1333')
  await iban.blur()
  await expect(page.locator('#entradas-iban .k5-field__error')).toHaveText(
    'Los dígitos de control del IBAN no coinciden. Revisa las cifras.',
  )
  await iban.focus()
  await page.keyboard.press('End')
  await page.keyboard.press('Backspace')
  await page.keyboard.type('2')
  await expect(iban).toHaveValue('ES91 2100 0418 4502 0005 1332')
  await expect(page.locator('#entradas-iban output')).toHaveText('ES9121000418450200051332')
  await expect(page.locator('#entradas-iban .k5-field__error')).toHaveCount(0)

  // AddressInput: pide tres letras, busca, se elige con el teclado y descarta respuestas tardías.
  const address = page.locator('#entradas-address input[role=combobox]')
  const options = page.locator('#entradas-address [role=option]')
  await address.fill('al')
  await expect(page.locator('#entradas-address .k5-combobox__empty')).toHaveText('Escribe al menos 3 caracteres.')
  await address.fill('alcal')
  await expect(options).toHaveCount(1)
  await expect(options.first()).toContainText('28014 Madrid')
  await page.keyboard.press('ArrowDown')
  await expect(address).toHaveAttribute('aria-activedescendant', await options.first().getAttribute('id'))
  await page.keyboard.press('Enter')
  await expect(page.locator('#entradas-address output')).toHaveText('alcala')
  await expect(address).toHaveValue('Calle de Alcalá, 48')
  await expect(address).toHaveAttribute('aria-expanded', 'false')
  await address.fill('gra')
  await page.waitForTimeout(80)
  await address.fill('gran')
  await expect(options).toHaveCount(1)
  await expect(options.first()).toContainText('Gran Vía, 32')
  await page.waitForTimeout(500)
  await expect(options).toHaveCount(1)
  await expect(page.locator('#entradas-address')).not.toContainText('Respuesta antigua')
  await address.fill('zzzz')
  await expect(page.locator('#entradas-address .k5-combobox__empty')).toHaveText('No hay resultados')
  await page.keyboard.press('Escape')
  await expect(address).toHaveValue('Calle de Alcalá, 48')
  await expect(page.locator('#entradas-address [role=listbox]')).toHaveCount(0)

  // Listas abiertas: sin errores de accesibilidad (sin animaciones, para medir los colores finales).
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await address.fill('calle')
  await expect(options).toHaveCount(3)
  await page.keyboard.press('ArrowDown')
  await axeOn(page, '#entradas-address', expect)
  await page.keyboard.press('Escape')
  await address.blur()
  await time.focus()
  await expect(page.locator('#entradas-time [role=listbox]')).toBeVisible()
  await axeOn(page, '#entradas-time', expect)
  await time.press('Escape')
  await time.blur()
  await page.emulateMedia({ reducedMotion: null })
}
